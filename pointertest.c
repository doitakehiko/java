#include <stdio.h>

int main() {
    // --------------------------------------------------
    // ① 普通の変数
    // --------------------------------------------------
    int a = 10; // 記号なし。aという箱に10を入れる

    // --------------------------------------------------
    // ② ポインタ型変数 ＆ ③ 変数へポインタを入れる
    // --------------------------------------------------
    int* p = &a; 
    // 型の後ろの「*」は、pがポインタ型（アドレス用の箱）であることを示す
    // 「&」は、aのメモリ上の住所（アドレス）を取り出す記号
    // これで、pは変数aの場所を指すようになる

    // --------------------------------------------------
    // ④ 変数に値をコピーする
    // --------------------------------------------------
    int b = a; // 「=」を使って、aの中身(10)をbにコピーする
    b = 20;    // bを書き換えても、コピー元であるaの中身は10のまま

    printf("aの値: %d, bの値: %d\n", a, b); 
    // 出力結果 -> aの値: 10, bの値: 20

    // --------------------------------------------------
    // ⑤ ポインタの参照元の値を変える
    // --------------------------------------------------
    *p = 50; 
    // 変数名の前の「*」は、「pが指している住所（aの箱）の中身」という意味
    // aの箱に直接50を叩き込む操作になる

    printf("aの値(書き換え後): %d\n", a); 
    // 出力結果 -> aの値(書き換え後): 50

    return 0;
}
